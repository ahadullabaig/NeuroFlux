"""
R5 — Table II, the ceiling across encoders, readouts and signals.

Reads the analysis tables `analyse_r5.py` writes and emits an IEEEtran
`table*`, in the style of R3's Table I (`figures_r3.py`).

Usage:
    uv run python scripts/r5_generality/analyse_r5.py --part encoders
    uv run python scripts/r5_generality/figures_r5.py
"""

from __future__ import annotations

import csv
import math
from pathlib import Path

ANALYSIS = Path("results/r5_generality/analysis")
FIGURES = Path("results/r5_generality/figures")

SIGNAL_COLUMNS: tuple[tuple[str, str], ...] = (
    ("mit-bih", "MIT-BIH"),
    ("synthetic-ecg", "Synth.\\ ECG"),
    ("eeg", "EEG"),
    ("sine", "2~Hz sine"),
)
# (encoder, readout family, row label)
ROWS: tuple[tuple[str, str, str], ...] = (
    ("poisson", "population", "Poisson & population"),
    ("poisson", "spike-rate", " & spike rate"),
    ("temporal", "latency", "Time to first spike & latency"),
    ("temporal", "population", " & population"),
    ("temporal", "spike-rate", " & spike rate"),
    ("delta", "population", "Delta & population"),
    ("delta", "spike-rate", " & spike rate"),
)


def load(name: str) -> list[dict[str, str]]:
    path = ANALYSIS / name
    if not path.exists():
        return []
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def fnum(value: str) -> float:
    return float(value) if value else math.nan


def family(readout: str) -> str:
    return readout.rsplit("-", 1)[0] if readout != "latency" else "latency"


def verdict_mark(test: dict[str, str]) -> str:
    """Table I's symbols, for an encoder's best readout against Poisson's."""
    if test["equivalent"] == "True":
        return "$\\equiv$"
    if test["significant"] == "True":
        return "$\\uparrow$" if fnum(test["median_diff"]) > 0 else "$\\downarrow$"
    return "--"


def table_2() -> None:
    cells = load("r5_encoder_cells.csv")
    tests = load("r5_t1_encoders.csv")
    if not cells or not tests:
        print("  Table II skipped: run analyse_r5.py --part encoders first")
        return

    def best_in_family(
        signal: str, rate: str, encoder: str, name: str
    ) -> dict[str, str]:
        candidates = [
            c
            for c in cells
            if c["signal"] == signal
            and c["output_rate_hz"] == rate
            and c["encoder"] == encoder
            and family(c["readout"]) == name
        ]
        return max(candidates, key=lambda c: fnum(c["compensated_clean"]))

    def cell(signal: str, rate: str, encoder: str, name: str) -> str:
        chosen = best_in_family(signal, rate, encoder, name)
        text = (
            f"${fnum(chosen['compensated_clean']):.2f}$ "
            f"(${fnum(chosen['causal_clean']):.2f}$)"
        )
        if encoder != "poisson" and chosen["best"] == "True":
            test = next(
                t
                for t in tests
                if t["signal"] == signal
                and t["output_rate_hz"] == rate
                and t["encoder"] == encoder
            )
            text += " " + verdict_mark(test)
        elif chosen["best"] == "True":
            text = f"{{\\boldmath {text}}}"
        return text

    lines = [
        "% Generated by scripts/r5_generality/figures_r5.py — do not edit.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{The Ceiling Across Encoders, Readouts and Signals}",
        "\\label{tab:generality}",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{5pt}",
        "\\begin{tabular}{ll" + "l" * len(SIGNAL_COLUMNS) + "}",
        "\\toprule",
        "Encoder & Readout & " + " & ".join(c[1] for c in SIGNAL_COLUMNS) + " \\\\",
    ]
    span = 2 + len(SIGNAL_COLUMNS)
    for rate, heading in (("40", "Output at 40~Hz"), ("5", "Output at 5~Hz")):
        lines += [
            "\\midrule",
            f"\\multicolumn{{{span}}}{{l}}{{\\emph{{{heading}}}}} \\\\",
        ]
        for encoder, name, label in ROWS:
            row = [cell(signal, rate, encoder, name) for signal, _ in SIGNAL_COLUMNS]
            lines.append(f"{label} & " + " & ".join(row) + " \\\\")
    notes = (
        "Noiseless-input output SNR in dB, median over records (MIT-BIH, $n=16$) "
        "or seeds ($n=10$), with the output advanced by its best lag in 0--64~ms; "
        "causal SNR in parentheses. Untrained $[32,16,8]$, encoder and hidden "
        "layer at 40~Hz. Each readout is shown at its best window (population "
        "$\\tau$ 10, 20 or 40~ms; spike-rate window 20, 40 or 80~ms). Bold: "
        "Poisson's best readout. For another encoder's best readout, against "
        "Poisson's: $\\equiv$ equivalent by TOST ($\\pm0.5$~dB); "
        "$\\uparrow$/$\\downarrow$ significant (Wilcoxon signed-rank, Holm "
        "across signals) and not equivalent; -- neither. Output SNR is flat in "
        "input SNR from 10 to 40~dB in every best-readout cell (slope interval "
        "below 1)."
    )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\\\[3pt]",
        "\\parbox{\\textwidth}{\\footnotesize " + notes + "}",
        "\\end{table*}",
        "",
    ]
    FIGURES.mkdir(parents=True, exist_ok=True)
    path = FIGURES / "table2_generality.tex"
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"  wrote {path}")


def main() -> None:
    table_2()


if __name__ == "__main__":
    main()
